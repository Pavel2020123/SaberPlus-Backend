import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../package.json', import.meta.url));
const bcrypt = require('bcrypt');

export async function verifyManagedAccounts(db, service, license) {
  const account = (rol, institucionId) => db.usuario.create({ data: { nombre: 'Synthetic LIC2', correo: `${randomUUID()}@example.invalid`, contrasenaHash: 'not-a-password', rol, correoVerificado: true, institucionId } });
  const institution = await db.institucion.create({ data: { nombre: 'LIC2 synthetic', codigoUnico: `LIC2-${randomUUID()}`, estadoVerificacion: 'APROBADA' } });
  const [admin, owner, teacher, stranger, personal] = await Promise.all([account('ADMIN'), account('PROFESOR', institution.id), account('PROFESOR', institution.id), account('PROFESOR'), account('ESTUDIANTE', institution.id)]);
  await db.miembroInstitucion.create({ data: { institucionId: institution.id, usuarioId: owner.id, rol: 'PROPIETARIO' } });
  const member = await db.miembroInstitucion.create({ data: { institucionId: institution.id, usuarioId: teacher.id, rol: 'PROFESOR' } });
  await license.acordar(admin.id, institution.id, { operacionId: randomUUID(), meses: 6, cuposEstudiantes: 2, cuposDocentes: 1, referenciaAcuerdo: 'Synthetic LIC2, no payment' }, false);
  await license.asignar(owner.id, institution.id, randomUUID(), teacher.id, 'DOCENTE');
  await license.aceptar(teacher.id, institution.id, randomUUID());
  const group = await db.clase.create({ data: { nombre: 'Synthetic group', codigoIngreso: randomUUID(), grado: 'ONCE', institucionId: institution.id } });
  const denied = status => e => e.getStatus?.() === status;
  const suffix = `colegio-${randomUUID()}.example`;
  await assert.rejects(service.solicitarSufijo(teacher.id, institution.id, randomUUID(), suffix), denied(403));
  const suffixOp = randomUUID();
  const request = await service.solicitarSufijo(owner.id, institution.id, suffixOp, suffix);
  assert.equal((await service.solicitarSufijo(owner.id, institution.id, suffixOp, suffix)).repetida, true);
  await assert.rejects(service.aprobarSufijo(owner.id, institution.id, randomUUID(), suffix, request.version), denied(403));
  await assert.rejects(service.aprobarSufijo(admin.id, institution.id, randomUUID(), suffix, request.version + 1), denied(409));
  await service.aprobarSufijo(admin.id, institution.id, randomUUID(), suffix, request.version);
  const duplicateInstitution = await db.institucion.create({ data: { nombre: 'Suffix collision synthetic', codigoUnico: randomUUID() } });
  await license.acordar(admin.id, duplicateInstitution.id, { operacionId: randomUUID(), meses: 6, cuposEstudiantes: 1, cuposDocentes: 0, referenciaAcuerdo: 'Synthetic suffix collision' }, false);
  const duplicateRequest = await service.solicitarSufijo(admin.id, duplicateInstitution.id, randomUUID(), suffix);
  await assert.rejects(service.aprobarSufijo(admin.id, duplicateInstitution.id, randomUUID(), suffix, duplicateRequest.version), denied(409));
  const csv = 'nombre,usuario\nAna,ana';
  await assert.rejects(service.previsualizar(stranger.id, institution.id, { csv, claseId: group.id }), denied(403));
  await assert.rejects(service.previsualizar(teacher.id, institution.id, { csv, claseId: group.id }), denied(403));
  const preview = await service.previsualizar(owner.id, institution.id, { csv, claseId: group.id });
  assert.equal(preview.puedeConfirmar, true);
  assert.equal(preview.disponibles, 2);
  assert.equal(await db.usuario.count({ where: { identificadorInstitucional: `ana@${suffix}` } }), 0);
  await assert.rejects(service.importar(owner.id, institution.id, randomUUID(), { csv, claseId: group.id }), denied(400));
  await assert.rejects(service.importar(owner.id, institution.id, randomUUID(), { csv: 'nombre,usuario\nOtra,otra', claseId: group.id, huella: preview.huella }), denied(409));
  await assert.rejects(service.importar(teacher.id, institution.id, randomUUID(), { csv, claseId: group.id, huella: preview.huella }), denied(403));
  assert.equal(await db.origenGestionadoInstitucional.count({ where: { institucionId: institution.id } }), 0);
  assert.equal(await db.asignacionLicenciaInstitucional.count({ where: { institucionId: institution.id, tipo: 'ESTUDIANTE' } }), 0);
  const operation = randomUUID();
  const imported = await service.importar(owner.id, institution.id, operation, { csv, claseId: group.id, huella: preview.huella });
  assert.equal(imported.creados, 1);
  assert.equal(imported.credenciales.length, 1);
  const credential = imported.credenciales[0];
  const user = await db.usuario.findUniqueOrThrow({ where: { id: credential.usuarioId }, include: { origenGestionadoLicencia: true } });
  assert.equal(user.correo, null);
  assert.equal(user.correoVerificado, false);
  assert.equal(user.identificadorInstitucional, `ana@${suffix}`);
  assert.equal(user.origenGestionadoLicencia.institucionId, institution.id);
  assert.equal(user.debeCambiarContrasena, true);
  assert.equal(user.versionSesion, 1);
  assert(await bcrypt.compare(credential.contrasenaTemporal, user.contrasenaHash));
  const replay = await service.importar(owner.id, institution.id, operation, { csv, claseId: group.id, huella: preview.huella });
  assert.equal(replay.repetida, true);
  assert.deepEqual(replay.credenciales, []);
  assert.equal(await db.asignacionLicenciaInstitucional.count({ where: { institucionId: institution.id, tipo: 'ESTUDIANTE', estado: 'ACTIVA' } }), 1);
  // A personal email cannot claim an institutional alias, including case changes.
  await assert.rejects(db.usuario.create({ data: { nombre: 'Collision', correo: user.identificadorInstitucional.toUpperCase(), contrasenaHash: 'unused' } }), e => e.code === 'P2002');
  await assert.rejects(service.restablecer(owner.id, institution.id, randomUUID(), personal.id), denied(404));
  await assert.rejects(service.restablecer(teacher.id, institution.id, randomUUID(), user.id), denied(403));
  await db.claseProfesor.create({ data: { claseId: group.id, miembroId: member.id } });
  assert.equal((await service.contexto(owner.id, institution.id)).puedeImportar, true);
  assert.equal((await service.contexto(teacher.id, institution.id)).puedeImportar, false);
  assert.equal((await service.grupos(owner.id, institution.id)).length, 1);
  await assert.rejects(service.grupos(teacher.id, institution.id), denied(403));
  assert.equal((await service.alumnos(teacher.id, institution.id, 1)).items.length, 1);
  await assert.rejects(service.alumnos(stranger.id, institution.id, 1), denied(403));
  await assert.rejects(service.alumnos(owner.id, institution.id, 0), denied(400));
  const resetOp = randomUUID();
  const reset = await service.restablecer(teacher.id, institution.id, resetOp, user.id);
  assert.equal(reset.credenciales.length, 1);
  assert.equal((await db.usuario.findUniqueOrThrow({ where: { id: user.id } })).versionSesion, 2);
  await assert.rejects(service.restablecer(owner.id, institution.id, resetOp, user.id), denied(409));
  assert.deepEqual((await service.restablecer(teacher.id, institution.id, resetOp, user.id)).credenciales, []);
  assert.equal((await db.usuario.findUniqueOrThrow({ where: { id: user.id } })).versionSesion, 2);
  const receipts = JSON.stringify(await db.operacionLicenciaInstitucional.findMany({ where: { institucionId: institution.id } }));
  const audits = JSON.stringify(await db.auditoriaInstitucion.findMany({ where: { institucionId: institution.id } }));
  for (const secret of [credential.contrasenaTemporal, reset.credenciales[0].contrasenaTemporal, user.contrasenaHash]) {
    assert(!receipts.includes(secret)); assert(!audits.includes(secret));
  }
  const candidates = ['beto', 'caro'];
  const otherGroup = await db.clase.create({ data: { nombre: 'Other synthetic group', codigoIngreso: randomUUID(), grado: 'ONCE', institucionId: institution.id } });
  const commands = await Promise.all(candidates.map(async nombre => {
    const contenido = `nombre,usuario\n${nombre},${nombre}`;
    const vista = await service.previsualizar(owner.id, institution.id, { csv: contenido, claseId: otherGroup.id });
    return { csv: contenido, claseId: otherGroup.id, huella: vista.huella };
  }));
  const race = await Promise.allSettled(commands.map(c => service.importar(owner.id, institution.id, randomUUID(), c)));
  assert.equal(race.filter(r => r.status === 'fulfilled').length, 1);
  assert([409, 429].includes(race.find(r => r.status === 'rejected').reason.getStatus()));
  assert.equal(await db.asignacionLicenciaInstitucional.count({ where: { institucionId: institution.id, tipo: 'ESTUDIANTE', estado: 'ACTIVA' } }), 2);
  assert.equal((await service.alumnos(owner.id, institution.id, 1)).items.length, 2);
  assert.equal((await service.alumnos(teacher.id, institution.id, 1)).items.length, 1);
  const otherStudent = await db.claseEstudiante.findFirstOrThrow({ where: { claseId: otherGroup.id } });
  await assert.rejects(service.restablecer(teacher.id, institution.id, randomUUID(), otherStudent.usuarioId), denied(403));
  for (let i = 0; i < 4; i++) await service.restablecer(owner.id, institution.id, randomUUID(), user.id);
  const beforeLimit = (await db.usuario.findUniqueOrThrow({ where: { id: user.id } })).versionSesion;
  await assert.rejects(service.restablecer(owner.id, institution.id, randomUUID(), user.id), denied(429));
  assert.equal((await db.usuario.findUniqueOrThrow({ where: { id: user.id } })).versionSesion, beforeLimit);
  // Prepare the independent actor envelope using owned synthetic audit events.
  await db.auditoriaInstitucion.createMany({ data: Array.from({ length: 16 }, () => ({ institucionId: institution.id, actorId: owner.id, accion: 'LIC2_RESET_TEMPORAL', detalle: { sintetico: true } })) });
  const otherVersion = (await db.usuario.findUniqueOrThrow({ where: { id: otherStudent.usuarioId } })).versionSesion;
  await assert.rejects(service.restablecer(owner.id, institution.id, randomUUID(), otherStudent.usuarioId), denied(429));
  assert.equal((await db.usuario.findUniqueOrThrow({ where: { id: otherStudent.usuarioId } })).versionSesion, otherVersion);
  await license.retirar(owner.id, institution.id, randomUUID(), teacher.id);
  await assert.rejects(service.restablecer(teacher.id, institution.id, randomUUID(), user.id), denied(403));
  console.log(JSON.stringify({ phase: 'lic2-managed-service-passed', localOnly: true, suffixReview: true, noFakeEmail: true, previewNoWrites: true, singleDeliveryNoSecretsStored: true, groupResetScope: true, retiredTeacherDenied: true, lastSeatRace: true, crossFieldIdentityCollision: true }));
}
